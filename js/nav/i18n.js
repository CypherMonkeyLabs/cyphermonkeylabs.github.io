function messages(lang) {
  switch (lang) {
    case "en":
      return en;
    case "es":
      return es;
    default: {
      const unknown = lang;
      throw new Error(`Unknown language: ${String(unknown)}`);
    }
  }
}

export function t(lang, key) {
  const table = messages(lang);
  if (table[key]) return table[key];
  if (en[key]) return en[key];
  return key;
}

export function tf(lang, key, vars = {}) {
  return t(lang, key).replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ));
}

export function languageKeys() {
  return { en: Object.keys(en), es: Object.keys(es) };
}

export function applyI18n(root, lang) {
  if (!root) return;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = t(lang, node.dataset.i18n);
    if (node.textContent !== value) node.textContent = value;
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(lang, node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    for (const part of node.dataset.i18nAttr.split(",")) {
      const index = part.indexOf(":");
      if (index < 0) continue;
      const attr = part.slice(0, index).trim();
      const key = part.slice(index + 1).trim();
      node.setAttribute(attr, t(lang, key));
    }
  });
}
