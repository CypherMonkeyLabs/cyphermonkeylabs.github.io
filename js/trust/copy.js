const COPY = { en, es };

export function resolveLang(value) {
  const lang = String(value || '').toLowerCase();
  if (lang.startsWith('es')) return 'es';
  return 'en';
}

export function strings(lang) {
  return COPY[resolveLang(lang)];
}

export function topicLabel(value, lang) {
  const labels = {
    general: { en: 'General', es: 'General' },
    correction: { en: 'Correction', es: 'Corrección' },
    'lab-idea': { en: 'Lab idea', es: 'Idea de lab' },
    collaboration: { en: 'Collaboration', es: 'Colaboración' },
    accessibility: { en: 'Accessibility issue', es: 'Problema de accesibilidad' },
  };
  const row = labels[value];
  if (!row) return value;
  return row[resolveLang(lang)];
}
